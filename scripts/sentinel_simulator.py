def compute_velocity_features(user: dict, current_ts: datetime, window_hours: list[int]) -> dict:
    """
    Compute count and sum features over multiple time windows.
    Uses _txn_history which stores (ts, amount) tuples.
    """
    feats = {}
    history = user["_txn_history"]
    for h in window_hours:
        cutoff = current_ts - timedelta(hours=h)
        window_txns = [(ts, amt) for ts, amt in history if ts >= cutoff]
        feats[f"count_{h}h"]      = len(window_txns)
        feats[f"sum_amount_{h}h"] = round(sum(amt for _, amt in window_txns), 2)
    return feats

def update_user_history(user: dict, ts: datetime, amount: float):
    """Append to rolling history, prune >7 days old."""
    user["_txn_history"].append((ts, amount))
    cutoff = ts - timedelta(days=7)
    user["_txn_history"] = [(t, a) for t, a in user["_txn_history"] if t >= cutoff]
    user["_txn_count_30d"]  += 1
    user["_amount_sum_30d"] += amount

def velocity_ratio(user: dict, count_24h: int) -> float:
    """How many times faster than the user's baseline is this 24h count?"""
    baseline_24h = user["velocity_baseline"]
    if baseline_24h == 0:
        return 0.0
    return round(count_24h / baseline_24h, 3)

def amount_ratio(user: dict, amount: float) -> float:
    """How many times the user's average transaction amount is this?"""
    if user["_txn_count_30d"] == 0:
        return 1.0
    avg = user["_amount_sum_30d"] / user["_txn_count_30d"]
    return round(amount / avg, 3) if avg > 0 else 1.0


