def validate_and_summarize(df: pd.DataFrame):
    print("\n" + "="*60)
    print("SIMULATION SUMMARY")
    print("="*60)

    total = len(df)
    fraud = df["is_fraud"].sum()
    print(f"Total transactions:  {total:>12,}")
    print(f"Fraud transactions:  {fraud:>12,}  ({fraud/total*100:.2f}%)")
    print(f"Legit transactions:  {total-fraud:>12,}  ({(total-fraud)/total*100:.2f}%)")

    print("\n── By client ──────────────────────────────")
    for client, grp in df.groupby("client_id"):
        f = grp["is_fraud"].sum()
        print(f"  {client:<20} {len(grp):>8,} txns  |  fraud: {f:>6,} ({f/len(grp)*100:.1f}%)")

    print("\n── By modality ────────────────────────────")
    for mod, grp in df.groupby("modality"):
        f = grp["is_fraud"].sum()
        print(f"  {mod:<10} {len(grp):>8,} txns  |  fraud: {f:>6,} ({f/len(grp)*100:.1f}%)")

    print("\n── Fraud types ────────────────────────────")
    fraud_df = df[df["is_fraud"]]
    if len(fraud_df) > 0:
        type_counts = fraud_df["fraud_type"].value_counts()
        for ft, cnt in type_counts.items():
            print(f"  {str(ft):<35} {cnt:>6,}")

    print("\n── Cross-modal fraud ──────────────────────")
    cross = df[df["cross_modality_fraud_id"].notna()]
    print(f"  Cross-modal transactions: {len(cross):,}")
    print(f"  Unique fraud sequences:   {cross['cross_modality_fraud_id'].nunique():,}")

    print("\n── Amount distribution (fiat) ─────────────")
    fiat = df[df["modality"] == "fiat"]["amount_usd"]
    if len(fiat) > 0:
        print(f"  Median:  ${fiat.median():>12,.2f}")
        print(f"  Mean:    ${fiat.mean():>12,.2f}")
        print(f"  P95:     ${fiat.quantile(0.95):>12,.2f}")
        print(f"  Max:     ${fiat.max():>12,.2f}")

    # Check shared identity_hash appears across multiple modalities
    cross_check = df.groupby("identity_hash")["modality"].nunique()
    multi_modal = (cross_check > 1).sum()
    print(f"\n── Identity cross-client check ────────────")
    print(f"  Identities in 2+ modalities: {multi_modal:,}")

    # Verify fraud rate targets
    print("\n── Fraud rate check ───────────────────────")
    fiat_df   = df[df["modality"] == "fiat"]
    crypto_df = df[df["modality"] == "crypto"]
